# PART 2: Sequential CPU Version (Baseline for Comparison)
# =============================================================================
def sobel_cpu_sequential(image):
    print("\n[CPU] Starting Sequential Edge Detection...")
    print("      (This is intentionally slow to demonstrate the need for GPUs)")

    start_time = time.time()

    height, width = image.shape
    output = np.zeros((height, width), dtype=np.int32)

    # Sobel Masks
    Gx = np.array([[-1, 0, 1], [-2, 0, 2], [-1, 0, 1]])
    Gy = np.array([[-1, -2, -1], [0, 0, 0], [1, 2, 1]])

    # Nested loops - The slow way!
    for y in range(1, height - 1):
        for x in range(1, width - 1):
            region = image[y-1:y+2, x-1:x+2]
            val_x = np.sum(region * Gx)
            val_y = np.sum(region * Gy)
            magnitude = int(np.sqrt(val_x**2 + val_y**2))
            if magnitude > 255: magnitude = 255
            output[y, x] = magnitude

    end_time = time.time()
    cpu_duration = end_time - start_time
    print(f"✅ [CPU] Done. Time taken: {cpu_duration:.4f} seconds")
    return output.astype(np.uint8), cpu_duration

