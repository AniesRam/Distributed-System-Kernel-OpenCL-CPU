# PART 3: OpenCL Host Code
# =============================================================================
def run_opencl_gpu(image):
    print("\n[GPU] Starting OpenCL Edge Detection...")

    # 1. Setup Platform & Device
    try:
        platform = cl.get_platforms()[0]
        device = platform.get_devices()[0] # Selects the first GPU found
        context = cl.Context([device])
        queue = cl.CommandQueue(context)
        print(f"      Device: {device.name}")
    except Exception as e:
        print("❌ [GPU] Error: No OpenCL device found. Make sure you are using a GPU runtime.")
        return None, 0

    # 2. Prepare Data
    height, width = image.shape
    host_input = image.flatten() # 1D array
    host_output = np.zeros_like(host_input)

    # 3. Memory Allocation (Create Buffers)
    mf = cl.mem_flags
    input_buf = cl.Buffer(context, mf.READ_ONLY | mf.COPY_HOST_PTR, hostbuf=host_input)
    output_buf = cl.Buffer(context, mf.WRITE_ONLY, host_input.nbytes)

    # 4. Compile Kernel
    program = cl.Program(context, kernel_code).build()

    # 5. Execute Kernel
    global_size = (width, height)
    local_size = None # Let the driver decide best work-group size

    start_time = time.time()

    # Enqueue the kernel
    program.sobel_filter(queue, global_size, local_size,
                         input_buf, output_buf,
                         np.int32(width), np.int32(height))

    # Wait for finish (synchronize) to get accurate timing
    queue.finish()

    end_time = time.time()
    gpu_duration = end_time - start_time

    # 6. Retrieve Results
    cl.enqueue_copy(queue, host_output, output_buf)
    result_image = host_output.reshape((height, width))

    print(f"✅ [GPU] Done. Time taken: {gpu_duration:.4f} seconds")
    return result_image, gpu_duration

